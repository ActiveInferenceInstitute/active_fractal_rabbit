"""Measure every gate arm and refresh the generated timing document.

``./run.sh bench`` runs this script. It asks ``run.sh --list`` for the arms, so
the arm set and the commands have one definition, then runs each arm once on
this host and writes ``docs/_generated/gate-timings.md``.

``--check`` verifies that the committed document still covers every arm and
carries a numeric duration for each; it does not re-run the arms.

Exit codes:
    0: the report was written, or the committed report is current in shape
    1: an arm failed, or the committed report is missing or incomplete
"""

from __future__ import annotations

import argparse
import os
import platform
import re
import subprocess
import sys
import time
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUN = ROOT / "run.sh"
REPORT = ROOT / "docs" / "_generated" / "gate-timings.md"
MARKER = "<!-- generated by scripts/gate_report.py; refresh with ./run.sh bench -->"

PYTEST_PASSED = re.compile(r"(\d+) passed")
PYTEST_SKIPPED = re.compile(r"(\d+) skipped")
PYTEST_FAILED = re.compile(r"(\d+) (?:failed|error)")
COVERAGE_TOTAL = re.compile(r"^TOTAL\b.*?(\d+(?:\.\d+)?)%\s*$", re.MULTILINE)
DOC_FILES = re.compile(r"relative links resolve across (\d+) Markdown files")
GNN_SUMMARY = re.compile(r"gnn conformance: .+")


def arms() -> list[str]:
    """Return the measurable arm names from the single entry point."""

    result = subprocess.run(
        ["bash", str(RUN), "--list"],
        cwd=str(ROOT),
        stdin=subprocess.DEVNULL,
        capture_output=True,
        text=True,
        timeout=60,
    )
    if result.returncode != 0:
        raise SystemExit(f"run.sh --list failed: {result.stderr.strip()}")
    return [line.strip() for line in result.stdout.splitlines() if line.strip()]


def _evidence(arm: str, output: str) -> str:
    if arm == "lint":
        return "ruff: no findings" if "Found" not in output else "ruff reported findings"
    if arm.startswith("test"):
        parts: list[str] = []
        for pattern, label in (
            (PYTEST_PASSED, "passed"),
            (PYTEST_SKIPPED, "skipped"),
            (PYTEST_FAILED, "failed"),
        ):
            match = pattern.search(output)
            if match:
                parts.append(f"{match.group(1)} {label}")
        coverage = COVERAGE_TOTAL.search(output)
        if coverage:
            parts.append(f"coverage {coverage.group(1)}%")
        return ", ".join(parts) or "no pytest summary"
    if arm == "docs":
        match = DOC_FILES.search(output)
        return f"{match.group(1)} Markdown files linked" if match else "link check ran"
    if arm == "gnn":
        match = GNN_SUMMARY.search(output)
        return match.group(0) if match else "conformance gate ran"
    return "ran"


def _load_average() -> str:
    try:
        return ", ".join(f"{value:.2f}" for value in os.getloadavg())
    except (AttributeError, OSError):
        return "unavailable"


def _worktree_state() -> str:
    result = subprocess.run(
        ["git", "status", "--porcelain"],
        cwd=str(ROOT),
        stdin=subprocess.DEVNULL,
        capture_output=True,
        text=True,
        timeout=60,
    )
    if result.returncode != 0:
        return "worktree state unknown"
    return "worktree clean" if not result.stdout.strip() else "worktree has local changes"


def _commit() -> str:
    result = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"],
        cwd=str(ROOT),
        stdin=subprocess.DEVNULL,
        capture_output=True,
        text=True,
        timeout=60,
    )
    return result.stdout.strip() if result.returncode == 0 else "unknown"


def measure(selected: list[str]) -> tuple[list[tuple[str, int, float, str]], int]:
    """Run each selected arm once and return rows plus a combined exit status."""

    rows: list[tuple[str, int, float, str]] = []
    status = 0
    for arm in selected:
        print(f"== {arm} ==", flush=True)
        started = time.monotonic()
        environment = dict(os.environ)
        environment["GATE_REPORT_BENCH"] = "1"
        result = subprocess.run(
            ["bash", str(RUN), arm],
            cwd=str(ROOT),
            env=environment,
            stdin=subprocess.DEVNULL,
            capture_output=True,
            text=True,
        )
        elapsed = time.monotonic() - started
        output = result.stdout + result.stderr
        print(output, end="" if output.endswith("\n") else "\n", flush=True)
        rows.append((arm, result.returncode, elapsed, _evidence(arm, output)))
        if result.returncode != 0:
            status = 1
    return rows, status


def render(rows: list[tuple[str, int, float, str]]) -> str:
    measured = datetime.now(tz=UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
    lines = [
        "# Gate arm timings",
        "",
        MARKER,
        "",
        "One run per arm on the host below, measured by `./run.sh bench`. Wall time",
        "includes the `uv run --frozen --extra dev` environment check. These are",
        "single-run observations, not a benchmark or a comparison between hosts.",
        "",
        f"- Measured: {measured}",
        f"- Commit: `{_commit()}` ({_worktree_state()})",
        f"- Host: `{platform.platform()}`",
        f"- Python: `{platform.python_version()}`",
        f"- Load average at write time: `{_load_average()}`",
        "",
        "| Arm | Command | Exit | Wall time (s) | Evidence |",
        "| --- | --- | --- | --- | --- |",
    ]
    for arm, code, elapsed, evidence in rows:
        lines.append(f"| `{arm}` | `./run.sh {arm}` | {code} | {elapsed:.2f} | {evidence} |")
    lines.append("")
    return "\n".join(lines)


def check(path: Path = REPORT) -> int:
    """Verify the committed report covers every arm with a numeric duration."""

    if not path.is_file():
        print(f"missing generated report: {path}", file=sys.stderr)
        return 1
    text = path.read_text(encoding="utf-8")
    if MARKER not in text:
        print(f"{path} is not the generated report", file=sys.stderr)
        return 1
    documented: dict[str, str] = {}
    for line in text.splitlines():
        if not line.startswith("| `"):
            continue
        cells = [cell.strip() for cell in line.strip("|").split("|")]
        if len(cells) < 5:
            continue
        documented[cells[0].strip("`")] = cells[3]
    expected = set(arms())
    missing = sorted(expected - set(documented))
    if missing:
        print(f"{path} is missing arms: {missing}", file=sys.stderr)
        return 1
    unmeasured = sorted(arm for arm, value in documented.items() if not re.fullmatch(r"\d+\.\d+", value))
    if unmeasured:
        print(f"{path} has no measured duration for: {unmeasured}", file=sys.stderr)
        return 1
    print(f"gate timings cover {len(expected)} arms")
    return 0


def _parse_report(path: Path) -> dict[str, tuple[str, int, float, str]]:
    """Read existing measured rows so a selective run can merge into them."""

    rows: dict[str, tuple[str, int, float, str]] = {}
    if not path.is_file():
        return rows
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("| `"):
            continue
        cells = [cell.strip() for cell in line.strip("|").split("|")]
        if len(cells) < 5:
            continue
        arm = cells[0].strip("`")
        try:
            rows[arm] = (arm, int(cells[2]), float(cells[3]), cells[4])
        except ValueError:
            continue
    return rows


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed report instead of re-measuring",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=REPORT,
        help=f"report path (default: {REPORT.relative_to(ROOT)})",
    )
    parser.add_argument(
        "--arms",
        nargs="+",
        choices=arms(),
        help="re-measure only these arms and merge them into the existing report",
    )
    args = parser.parse_args(argv)

    if args.check:
        return check(args.output)

    selected = args.arms or arms()
    measured, status = measure(selected)
    if args.arms:
        existing = _parse_report(args.output)
        for row in measured:
            existing[row[0]] = row
        rows = [existing[arm] for arm in arms() if arm in existing]
    else:
        rows = measured
    args.output.parent.mkdir(parents=True, exist_ok=True)
    temporary = args.output.with_suffix(".md.tmp")
    temporary.write_text(render(rows), encoding="utf-8")
    temporary.replace(args.output)
    print(f"wrote {args.output.relative_to(ROOT)}")
    return status


if __name__ == "__main__":
    raise SystemExit(main())
